"use client";

import { useEffect, useMemo, useState } from "react";
import {
  Languages, Plus, Trash2, Sparkles, Loader2, Download, Copy, Check, AlertTriangle,
  AlertOctagon, Info, Cpu, History, ArrowRight, ShieldCheck,
} from "lucide-react";
import {
  runTranslationGuard, fetchTGCampaigns, fetchTGCampaign, fetchTGLanguages,
  TGCampaign, TGCampaignSummary, TGTranslation, TGFinding, TGLanguages, TGScores,
} from "@/lib/api";

const CARD = "bg-white border border-slate-200/80 shadow-soft rounded-2xl";
const MAX_TRANSLATIONS = 8;

// Example from the product brief: the same claim in three languages.
const EXAMPLE = {
  title: "Laptop battery launch — India",
  source: "Our laptop provides up to 12 hours of battery life. Now at ₹79,999.",
  translations: [
    { label: "Tamil", text: "எங்கள் லேப்டாப் 12 மணி நேர பேட்டரி ஆயுளை வழங்குகிறது. இப்போது ₹79,999." },
    { label: "Hindi", text: "हमारा लैपटॉप 12 घंटे से अधिक बैटरी लाइफ देता है। अब सिर्फ ₹69,999 में।" },
    { label: "French", text: "Notre ordinateur portable offre jusqu'à 12 heures d'autonomie. Désormais à 79 999 ₹." },
  ],
};

const SCORE_LABELS: { key: keyof TGScores; label: string; hint: string }[] = [
  { key: "numerical_consistency", label: "Numbers & prices", hint: "Figures, units and prices match the source" },
  { key: "claim_consistency", label: "Claim qualifiers", hint: "“up to” / “more than” / “about” kept the same" },
  { key: "completeness", label: "Completeness", hint: "No figure from the source is missing" },
  { key: "terminology_consistency", label: "Brand terms", hint: "Approved product names kept exactly" },
  { key: "negation_consistency", label: "Negations", hint: "No / not / without carried over" },
  { key: "semantic_similarity", label: "Meaning (AI)", hint: "AI judgement of overall meaning" },
];

function verdictStyle(v: string) {
  if (v === "Needs revision") return "bg-rose-50 text-rose-700 ring-rose-200";
  if (v === "Review recommended") return "bg-amber-50 text-amber-700 ring-amber-200";
  return "bg-emerald-50 text-emerald-700 ring-emerald-200";
}
function scoreColor(n: number) {
  if (n >= 85) return "bg-emerald-500";
  if (n >= 60) return "bg-amber-500";
  return "bg-rose-500";
}
function sevStyle(s: string) {
  if (s === "CRITICAL") return { box: "border-rose-200 bg-rose-50/40", chip: "bg-rose-100 text-rose-700", Icon: AlertOctagon, icon: "text-rose-600" };
  if (s === "WARNING") return { box: "border-amber-200 bg-amber-50/40", chip: "bg-amber-100 text-amber-700", Icon: AlertTriangle, icon: "text-amber-600" };
  return { box: "border-slate-200 bg-slate-50/60", chip: "bg-slate-100 text-slate-600", Icon: Info, icon: "text-slate-500" };
}
const STATUS_STYLE: Record<string, string> = {
  match: "bg-emerald-50 text-emerald-700",
  changed: "bg-rose-50 text-rose-700",
  qualifier: "bg-amber-50 text-amber-700",
  missing: "bg-amber-50 text-amber-700",
  additional: "bg-sky-50 text-sky-700",
};
const STATUS_LABEL: Record<string, string> = {
  match: "Match", changed: "Changed", qualifier: "Qualifier changed", missing: "Missing", additional: "Added",
};

function buildReport(c: TGCampaign): string {
  const lines = [
    `# Translation Guard report — ${c.title}`,
    "",
    `- Source language: ${c.source_language}`,
    `- Overall verdict: **${c.verdict}** (lowest score ${c.overall_score}/100)`,
    `- Engine: ${c.engine}`,
    `- Run by: ${c.created_by || "—"} on ${c.created_at ? new Date(c.created_at + "Z").toLocaleString() : "—"}`,
    "",
    "## Source text",
    "",
    c.source_text,
    "",
  ];
  c.translations.forEach((t, i) => {
    lines.push(`## ${i + 1}. ${t.label || t.language.name} (${t.language.name}) — ${t.verdict}, ${t.overall_score}/100`, "");
    lines.push(t.text, "");
    lines.push("| Check | Score |", "|---|---|");
    SCORE_LABELS.forEach((s) => lines.push(`| ${s.label} | ${t.scores[s.key] ?? "n/a"} |`));
    lines.push("");
    if (t.findings.length) {
      lines.push("### Findings", "");
      t.findings.forEach((f) => {
        lines.push(`- **${f.severity}** — ${f.title} _(${f.engine.startsWith("llm") ? "AI" : "rule-based"})_`);
        if (f.explanation && f.explanation !== f.title) lines.push(`  - ${f.explanation}`);
        if (f.suggestion) lines.push(`  - Suggested fix: ${f.suggestion}`);
        if (f.evidence) lines.push(`  - Evidence: ${f.evidence}`);
      });
      lines.push("");
    }
    if (t.corrected_translation) lines.push("### Suggested corrected translation (AI — needs human review)", "", t.corrected_translation, "");
  });
  lines.push("---", "Generated by BrandVault AI Translation Guard. AI suggestions require human review before use.");
  return lines.join("\n");
}

export default function TranslationGuardPage() {
  const [title, setTitle] = useState("");
  const [source, setSource] = useState("");
  const [rows, setRows] = useState<{ label: string; text: string }[]>([{ label: "", text: "" }]);
  const [useAI, setUseAI] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<TGCampaign | null>(null);
  const [active, setActive] = useState(0);
  const [history, setHistory] = useState<TGCampaignSummary[]>([]);
  const [langs, setLangs] = useState<TGLanguages | null>(null);
  const [copied, setCopied] = useState(false);

  const loadHistory = () => fetchTGCampaigns().then(setHistory).catch(() => setHistory([]));
  useEffect(() => {
    loadHistory();
    fetchTGLanguages().then(setLangs).catch(() => setLangs(null));
  }, []);

  const canRun = source.trim() && rows.some((r) => r.text.trim()) && !busy;

  const run = async () => {
    if (!canRun) return;
    setBusy(true);
    setError(null);
    try {
      const c = await runTranslationGuard({
        title: title.trim() || "Multilingual campaign",
        source_text: source.trim(),
        translations: rows.filter((r) => r.text.trim()).map((r) => ({ label: r.label.trim() || undefined, text: r.text.trim() })),
        use_ai: useAI,
      });
      setResult(c);
      setActive(0);
      loadHistory();
    } catch (e: any) {
      setError(e?.message || "Analysis failed. Make sure the backend is running.");
    } finally {
      setBusy(false);
    }
  };

  const openCampaign = async (id: string) => {
    setError(null);
    try {
      const c = await fetchTGCampaign(id);
      setResult(c);
      setActive(0);
      setTitle(c.title);
      setSource(c.source_text);
      setRows(c.translations.map((t) => ({ label: t.label || "", text: t.text })));
    } catch (e: any) {
      setError(e?.message || "Could not open that campaign.");
    }
  };

  const loadExample = () => {
    setTitle(EXAMPLE.title);
    setSource(EXAMPLE.source);
    setRows(EXAMPLE.translations.map((t) => ({ ...t })));
    setResult(null);
  };

  const download = () => {
    if (!result) return;
    const blob = new Blob([buildReport(result)], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `translation-guard-${result.title.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const t: TGTranslation | undefined = result?.translations[active];
  const counts = useMemo(() => {
    const f = t?.findings || [];
    return { critical: f.filter((x) => x.severity === "CRITICAL").length, warning: f.filter((x) => x.severity === "WARNING").length };
  }, [t]);

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col lg:flex-row lg:items-end justify-between gap-4">
        <div>
          <div className="inline-flex items-center gap-1.5 text-xs font-semibold text-indigo-600 mb-1.5">
            <Languages className="w-3.5 h-3.5" /> Translation Guard
          </div>
          <h2 className="text-2xl font-bold tracking-tight text-slate-900">Every language should make the same claim</h2>
          <p className="text-[13px] text-slate-600 mt-1 max-w-2xl">
            Compare each translation with the source. Numbers, prices, “up to / more than” qualifiers, negations and product
            names are checked exactly; an AI pass adds a meaning score and a corrected translation.
          </p>
        </div>
        {langs && (
          <div className={`shrink-0 inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-xs font-semibold ring-1 ${langs.ai_available ? "bg-violet-50 text-violet-700 ring-violet-200" : "bg-slate-100 text-slate-600 ring-slate-200"}`}>
            <Cpu className="w-3.5 h-3.5" />
            {langs.ai_available ? "AI meaning check available" : "Rule-based checks only (no AI model configured)"}
          </div>
        )}
      </div>

      <div className="grid grid-cols-1 xl:grid-cols-12 gap-6 items-start">
        {/* -------------------------------- Input -------------------------------- */}
        <div className="xl:col-span-5 space-y-4">
          <div className={`${CARD} p-5 space-y-4`}>
            <div className="flex items-center justify-between">
              <h3 className="text-sm font-bold text-slate-900">Source campaign</h3>
              <button onClick={loadExample} className="text-xs font-semibold text-indigo-600 hover:text-indigo-800 hover:underline">
                Load example
              </button>
            </div>
            <div>
              <label htmlFor="tg-title" className="text-xs font-medium text-slate-600 block mb-1">Campaign name</label>
              <input id="tg-title" value={title} onChange={(e) => setTitle(e.target.value)} placeholder="e.g. Diwali laptop launch"
                     className="w-full h-10 px-3 text-sm bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:border-indigo-500 focus:bg-white transition-colors" />
            </div>
            <div>
              <label htmlFor="tg-source" className="text-xs font-medium text-slate-600 block mb-1">Original text (any language)</label>
              <textarea id="tg-source" value={source} onChange={(e) => setSource(e.target.value)} rows={4} maxLength={5000}
                        placeholder="Paste the approved original copy…"
                        className="w-full text-sm bg-slate-50 border border-slate-200 rounded-xl p-3 focus:outline-none focus:border-indigo-500 focus:bg-white resize-y leading-relaxed transition-colors" />
            </div>
          </div>

          <div className={`${CARD} p-5 space-y-3`}>
            <div className="flex items-center justify-between">
              <h3 className="text-sm font-bold text-slate-900">Translations <span className="text-slate-400 font-medium">({rows.length}/{MAX_TRANSLATIONS})</span></h3>
              <button
                onClick={() => setRows((r) => (r.length < MAX_TRANSLATIONS ? [...r, { label: "", text: "" }] : r))}
                disabled={rows.length >= MAX_TRANSLATIONS}
                className="inline-flex items-center gap-1 h-8 px-2.5 rounded-lg text-xs font-semibold text-indigo-700 bg-indigo-50 hover:bg-indigo-100 disabled:opacity-40 transition-colors"
              >
                <Plus className="w-3.5 h-3.5" /> Add language
              </button>
            </div>
            {rows.map((r, i) => (
              <div key={i} className="rounded-xl border border-slate-200 bg-slate-50/50 p-3 space-y-2">
                <div className="flex items-center gap-2">
                  <input value={r.label} onChange={(e) => setRows((rs) => rs.map((x, j) => (j === i ? { ...x, label: e.target.value } : x)))}
                         placeholder={`Label (optional) — language is detected`} aria-label={`Translation ${i + 1} label`}
                         className="flex-1 h-8 px-2.5 text-xs bg-white border border-slate-200 rounded-lg focus:outline-none focus:border-indigo-500" />
                  <button onClick={() => setRows((rs) => (rs.length > 1 ? rs.filter((_, j) => j !== i) : [{ label: "", text: "" }]))}
                          className="p-2 rounded-lg text-slate-400 hover:text-rose-600 hover:bg-rose-50 transition-colors" aria-label={`Remove translation ${i + 1}`}>
                    <Trash2 className="w-3.5 h-3.5" />
                  </button>
                </div>
                <textarea value={r.text} onChange={(e) => setRows((rs) => rs.map((x, j) => (j === i ? { ...x, text: e.target.value } : x)))}
                          rows={3} maxLength={5000} placeholder="Paste the translated copy…" aria-label={`Translation ${i + 1} text`}
                          className="w-full text-sm bg-white border border-slate-200 rounded-lg p-2.5 focus:outline-none focus:border-indigo-500 resize-y leading-relaxed" />
              </div>
            ))}

            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pt-2">
              <label className={`inline-flex items-center gap-2 text-xs ${langs?.ai_available ? "text-slate-700" : "text-slate-400"}`}>
                <input type="checkbox" checked={useAI && !!langs?.ai_available} disabled={!langs?.ai_available}
                       onChange={(e) => setUseAI(e.target.checked)} className="w-4 h-4 accent-indigo-600" />
                Include AI meaning check
              </label>
              <button onClick={run} disabled={!canRun}
                      className="h-10 px-5 inline-flex items-center justify-center gap-2 rounded-xl text-sm font-semibold text-white bg-gradient-to-r from-indigo-600 to-violet-600 hover:from-indigo-700 hover:to-violet-700 disabled:opacity-40 shadow-md shadow-indigo-500/20 transition-all">
                {busy ? <Loader2 className="w-4 h-4 animate-spin" /> : <Sparkles className="w-4 h-4" />}
                {busy ? "Checking translations…" : "Run Translation Guard"}
              </button>
            </div>
            {error && <div role="alert" className="text-xs text-rose-700 bg-rose-50 border border-rose-200 rounded-lg px-3 py-2">{error}</div>}
          </div>

          {/* History */}
          <div className={`${CARD} p-5`}>
            <h3 className="text-sm font-bold text-slate-900 flex items-center gap-2"><History className="w-4 h-4 text-slate-400" /> Recent checks</h3>
            {history.length === 0 ? (
              <p className="text-xs text-slate-500 mt-2">No checks yet. Run one to see it here.</p>
            ) : (
              <ul className="mt-3 divide-y divide-slate-100">
                {history.slice(0, 8).map((h) => (
                  <li key={h.id}>
                    <button onClick={() => openCampaign(h.id)} className="w-full py-2.5 flex items-center justify-between gap-3 text-left group">
                      <div className="min-w-0">
                        <div className="text-[13px] font-semibold text-slate-800 truncate group-hover:text-indigo-700">{h.title}</div>
                        <div className="text-[11px] text-slate-500">
                          {h.source_language} → {h.languages.map((l) => l.toUpperCase()).join(", ")}
                          {h.created_at && ` · ${new Date(h.created_at + "Z").toLocaleDateString()}`}
                        </div>
                      </div>
                      <span className={`shrink-0 text-[11px] font-semibold px-2 py-0.5 rounded-full ring-1 ${verdictStyle(h.verdict)}`}>{h.verdict}</span>
                    </button>
                  </li>
                ))}
              </ul>
            )}
          </div>
        </div>

        {/* ------------------------------- Results ------------------------------- */}
        <div className="xl:col-span-7 space-y-4">
          {!result ? (
            <div className={`${CARD} p-10 text-center`}>
              <div className="mx-auto w-12 h-12 rounded-2xl bg-indigo-50 text-indigo-600 flex items-center justify-center">
                <Languages className="w-6 h-6" />
              </div>
              <h3 className="mt-4 text-base font-bold text-slate-900">No results yet</h3>
              <p className="mt-1 text-[13px] text-slate-500 max-w-md mx-auto">
                Add the original copy and at least one translation, then run the check. Try the example: the Hindi version
                turns “up to 12 hours” into “more than 12 hours” and changes the price.
              </p>
              {langs && (
                <p className="mt-4 text-[11px] text-slate-400 max-w-md mx-auto">
                  Qualifier and negation checks: {langs.qualifier_and_negation_checks.map((l) => l.name).join(", ")}. Other languages get
                  number, price and brand-term checks{langs.ai_available ? " plus the AI review" : ""}.
                </p>
              )}
            </div>
          ) : (
            <>
              {/* Summary */}
              <div className={`${CARD} p-5`}>
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                  <div className="min-w-0">
                    <div className="text-xs text-slate-500">{result.source_language} source · {result.translations.length} translation(s)</div>
                    <h3 className="text-lg font-bold text-slate-900 truncate">{result.title}</h3>
                  </div>
                  <div className="flex items-center gap-2">
                    <span className={`text-xs font-semibold px-2.5 py-1 rounded-full ring-1 ${verdictStyle(result.verdict)}`}>{result.verdict}</span>
                    <button onClick={download} className="h-9 px-3 inline-flex items-center gap-1.5 rounded-xl text-xs font-semibold text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 transition-colors">
                      <Download className="w-3.5 h-3.5" /> Report
                    </button>
                  </div>
                </div>
                <div className="mt-4 flex flex-wrap gap-2" role="tablist" aria-label="Translations">
                  {result.translations.map((tr, i) => (
                    <button key={tr.id} role="tab" aria-selected={i === active} onClick={() => setActive(i)}
                            className={`h-10 pl-3 pr-2 inline-flex items-center gap-2 rounded-xl text-[13px] font-semibold border transition-all ${i === active ? "bg-indigo-50 border-indigo-200 text-indigo-800 shadow-sm" : "bg-white border-slate-200 text-slate-600 hover:border-slate-300"}`}>
                      {tr.label || tr.language.name}
                      <span className={`text-[11px] font-bold text-white px-1.5 py-0.5 rounded-md ${scoreColor(tr.overall_score)}`}>{tr.overall_score}</span>
                    </button>
                  ))}
                </div>
              </div>

              {t && (
                <>
                  {/* Language + scores */}
                  <div className={`${CARD} p-5`}>
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <div className="flex items-center gap-2 flex-wrap">
                        <span className={`text-xs font-semibold px-2.5 py-1 rounded-full ring-1 ${verdictStyle(t.verdict)}`}>{t.verdict}</span>
                        <span className="text-xs text-slate-600">
                          Detected <b className="text-slate-900">{t.language.name}</b> · {Math.round(t.language.confidence * 100)}% confidence
                        </span>
                      </div>
                      <span className="text-[11px] text-slate-500">
                        {counts.critical} critical · {counts.warning} warnings
                      </span>
                    </div>
                    {!t.qualifier_check_supported && (
                      <p className="mt-3 text-[11px] text-amber-700 bg-amber-50 border border-amber-200 rounded-lg px-3 py-2">
                        Qualifier and negation checks are not available for {t.language.name} yet. Numbers, prices and brand terms were still checked.
                      </p>
                    )}
                    <div className="mt-4 grid grid-cols-1 sm:grid-cols-2 gap-x-6 gap-y-3">
                      {SCORE_LABELS.map((s) => {
                        const v = t.scores[s.key];
                        return (
                          <div key={s.key} title={s.hint}>
                            <div className="flex items-center justify-between text-xs">
                              <span className="font-medium text-slate-700">{s.label}</span>
                              <span className="font-semibold tabular-nums text-slate-900">{v === null ? <span className="text-slate-400 font-medium">n/a</span> : `${v}`}</span>
                            </div>
                            <div className="mt-1.5 h-1.5 rounded-full bg-slate-100 overflow-hidden">
                              {v !== null && <div className={`h-full rounded-full ${scoreColor(v)}`} style={{ width: `${v}%` }} />}
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  </div>

                  {/* Side by side */}
                  <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                    <div className={`${CARD} p-4`}>
                      <div className="text-xs font-semibold text-slate-500 mb-1.5">Original · {result.source_language}</div>
                      <p className="text-sm text-slate-800 leading-relaxed whitespace-pre-wrap">{result.source_text}</p>
                    </div>
                    <div className={`${CARD} p-4`}>
                      <div className="text-xs font-semibold text-slate-500 mb-1.5">Translation · {t.language.name}</div>
                      <p className="text-sm text-slate-800 leading-relaxed whitespace-pre-wrap">{t.text}</p>
                    </div>
                  </div>

                  {/* Numbers table */}
                  {t.numbers.length > 0 && (
                    <div className={`${CARD} overflow-hidden`}>
                      <div className="px-5 pt-4 pb-2 text-sm font-bold text-slate-900">Figures and claims</div>
                      <div className="overflow-x-auto">
                        <table className="w-full text-[13px]">
                          <thead>
                            <tr className="text-left text-xs text-slate-500 border-y border-slate-100 bg-slate-50/60">
                              <th className="px-5 py-2 font-medium">Source</th>
                              <th className="px-3 py-2 font-medium">Translation</th>
                              <th className="px-5 py-2 font-medium text-right">Status</th>
                            </tr>
                          </thead>
                          <tbody>
                            {t.numbers.map((n, i) => (
                              <tr key={i} className="border-b border-slate-100 last:border-0">
                                <td className="px-5 py-2.5 text-slate-800">{n.source ?? <span className="text-slate-400">—</span>}</td>
                                <td className="px-3 py-2.5 text-slate-800">{n.translation ?? <span className="text-slate-400">—</span>}</td>
                                <td className="px-5 py-2.5 text-right">
                                  <span className={`text-[11px] font-semibold px-2 py-0.5 rounded-full ${STATUS_STYLE[n.status]}`}>{STATUS_LABEL[n.status]}</span>
                                </td>
                              </tr>
                            ))}
                          </tbody>
                        </table>
                      </div>
                    </div>
                  )}

                  {/* Findings */}
                  <div className={`${CARD} p-5`}>
                    <h4 className="text-sm font-bold text-slate-900">Findings</h4>
                    {t.findings.length === 0 ? (
                      <div className="mt-3 flex items-center gap-2 text-[13px] text-emerald-700 bg-emerald-50 border border-emerald-200 rounded-xl px-3 py-2.5">
                        <ShieldCheck className="w-4 h-4" /> No differences found in the checked claims.
                      </div>
                    ) : (
                      <ul className="mt-3 space-y-2.5">
                        {t.findings.map((f: TGFinding, i) => {
                          const st = sevStyle(f.severity);
                          const ai = f.engine.startsWith("llm");
                          return (
                            <li key={i} className={`rounded-xl border p-3.5 ${st.box}`}>
                              <div className="flex items-start gap-2.5">
                                <st.Icon className={`w-4 h-4 mt-0.5 shrink-0 ${st.icon}`} aria-hidden />
                                <div className="min-w-0 flex-1">
                                  <div className="flex flex-wrap items-center gap-1.5">
                                    <span className={`text-[10px] font-bold px-1.5 py-0.5 rounded ${st.chip}`}>{f.severity}</span>
                                    <span className={`text-[10px] font-semibold px-1.5 py-0.5 rounded ${ai ? "bg-violet-100 text-violet-700" : "bg-slate-100 text-slate-600"}`}>
                                      {ai ? "AI · needs review" : "Rule-based"}
                                    </span>
                                    {f.confirmed_by_ai && (
                                      <span className="text-[10px] font-semibold px-1.5 py-0.5 rounded bg-violet-100 text-violet-700">Confirmed by AI</span>
                                    )}
                                  </div>
                                  <div className="mt-1.5 text-[13px] font-semibold text-slate-900">{f.title}</div>
                                  {f.explanation && f.explanation !== f.title && <p className="mt-0.5 text-xs text-slate-600 leading-relaxed">{f.explanation}</p>}
                                  {(f.original || f.translated) && (
                                    <div className="mt-2 grid grid-cols-1 sm:grid-cols-2 gap-2 text-xs">
                                      {f.original && <div className="rounded-lg bg-white/80 border border-slate-200 px-2.5 py-1.5"><span className="text-slate-400">Source: </span>{f.original}</div>}
                                      {f.translated && <div className="rounded-lg bg-white/80 border border-slate-200 px-2.5 py-1.5"><span className="text-slate-400">Translation: </span>{f.translated}</div>}
                                    </div>
                                  )}
                                  {f.suggestion && (
                                    <div className="mt-2 inline-flex items-start gap-1.5 text-xs text-indigo-700">
                                      <ArrowRight className="w-3.5 h-3.5 mt-px shrink-0" /> {f.suggestion}
                                    </div>
                                  )}
                                  {f.evidence && <div className="mt-1 text-[11px] text-slate-500">Evidence: {f.evidence}</div>}
                                </div>
                              </div>
                            </li>
                          );
                        })}
                      </ul>
                    )}
                  </div>

                  {/* Corrected translation + cultural notes */}
                  <div className={`${CARD} p-5`}>
                    <div className="flex items-center justify-between gap-2">
                      <h4 className="text-sm font-bold text-slate-900">Suggested corrected translation</h4>
                      {t.corrected_translation && (
                        <button
                          onClick={() => { navigator.clipboard?.writeText(t.corrected_translation).then(() => { setCopied(true); setTimeout(() => setCopied(false), 1500); }).catch(() => {}); }}
                          className="h-8 px-2.5 inline-flex items-center gap-1.5 rounded-lg text-xs font-semibold text-slate-700 bg-white border border-slate-200 hover:bg-slate-50">
                          {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />} {copied ? "Copied" : "Copy"}
                        </button>
                      )}
                    </div>
                    {t.corrected_translation ? (
                      <>
                        <p className="mt-2 text-sm text-slate-800 leading-relaxed whitespace-pre-wrap rounded-xl bg-violet-50/50 border border-violet-100 p-3">{t.corrected_translation}</p>
                        <p className="mt-2 text-[11px] text-slate-500">Generated by {t.model || "the AI model"}. A fluent reviewer should check it before publishing.</p>
                      </>
                    ) : (
                      <p className="mt-2 text-xs text-slate-500">
                        {langs?.ai_available ? "Run with the AI meaning check switched on to get a corrected translation." : "Configure an AI model on the server to get corrected translations. Rule-based checks above are complete."}
                      </p>
                    )}
                    {t.cultural_notes.length > 0 && (
                      <div className="mt-4">
                        <div className="text-xs font-semibold text-slate-700">Cultural and regional notes <span className="font-medium text-violet-600">(AI · needs human review)</span></div>
                        <ul className="mt-1.5 list-disc pl-5 text-xs text-slate-600 space-y-1">
                          {t.cultural_notes.map((n, i) => <li key={i}>{n}</li>)}
                        </ul>
                      </div>
                    )}
                  </div>
                </>
              )}
            </>
          )}
        </div>
      </div>
    </div>
  );
}
